def traducir_categorias(item_categories: pd.DataFrame) -> pd.DataFrame:
    """Agrega columnas en español: categoria_grupo y categoria_nombre."""
    out = item_categories.copy()
    out["categoria_grupo"] = out["item_category_id"].map(lambda i: CATEGORIAS[i][0])
    out["categoria_nombre"] = out["item_category_id"].map(lambda i: CATEGORIAS[i][1])
    return out


def traducir_tiendas(shops: pd.DataFrame) -> pd.DataFrame:
    """Agrega columnas en español: ciudad, tienda_nombre y tienda_tipo."""
    out = shops.copy()
    out["ciudad"] = out["shop_id"].map(lambda i: TIENDAS[i][0])
    out["tienda_nombre"] = out["shop_id"].map(lambda i: TIENDAS[i][1])
    out["tienda_tipo"] = out["shop_id"].map(lambda i: TIENDAS[i][2])
    return out
